WRAPPER = '''#!/usr/bin/env bash
# ============================================================================
# {slug}_{topic}_fullrun.sh — {name} on {label}
#
# Generated by `rceval adapter init`. Read real_eval/docs/wrapper_interface.md
# for what each variable below means, and automation/{topic}_contract.md for
# what this framework must produce.
# ============================================================================

set -euo pipefail

ROOT="${{RESEARCHCLAWEVAL_ROOT:-$(cd "$(dirname "${{BASH_SOURCE[0]}}")/../.." && pwd)}}"
source "$ROOT/real_eval/scripts/lib_real_eval.sh"

# ── Identity ────────────────────────────────────────────────────────────────
export FRAMEWORK_NAME="{name}"
export FRAMEWORK_SLUG="{slug}_{topic}_fullrun"
export FRAMEWORK_SRC="${{RESEARCHCLAWEVAL_{envid}_ROOT:-$ROOT/{name}}}"

# ── Required ────────────────────────────────────────────────────────────────
export FRAMEWORK_RUNTIME_KIND="docker"

export FRAMEWORK_ENTRY_PATHS=$(cat <<'EOF'
{entry_paths}
EOF
)

export FRAMEWORK_PROVIDER_INJECTION="{injection}"

# Native-execution proof. Must be echoed by the framework from INSIDE its own
# execution. A run that exits 0 without this string in the log is judged
# non-native and is not scored.
export FRAMEWORK_NATIVE_LOG_MARKER="{marker}"

# ── Runtime ─────────────────────────────────────────────────────────────────
export FRAMEWORK_RUNTIME_IMAGE="{image}"
export FRAMEWORK_NATIVE_ENTRYPOINT="{entrypoint}"
export FRAMEWORK_COMMAND_LABEL="{entrypoint} (non-interactive)"
export FRAMEWORK_EXECUTOR_KIND="framework_cli"

export FRAMEWORK_DOCKER_ARGS=$(cat <<'EOF'
{name_upper}_MAX_AGENT_TURNS=100
EOF
)

# ── Provider ────────────────────────────────────────────────────────────────
# The provider config belongs to the caller; api/ is git-ignored here.
: "${{PROVIDER_CONFIG:?set PROVIDER_CONFIG to your provider TOML before running}}"

# ── The command executed inside the container ───────────────────────────────
export FRAMEWORK_RUNTIME_COMMAND=$(cat <<'EOF'
set -euo pipefail

echo "{marker}"

mkdir -p /workspace/input
cp /input/{contract_name} /workspace/input/contract.md

# TODO: drive your framework here. It must own idea formation, experiment
# design, execution, comparison, selection and artifact delivery, and must
# write the artifacts named in automation/{topic}_contract.md to /workspace.
#
# {entrypoint} < /workspace/input/contract.md
EOF
)

exec "$ROOT"/real_eval/scripts/{runner}
'''


def slugify(name: str) -> str:
    """Lowercase, underscore-separated identifier derived from a framework name."""
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    if not slug:
        raise ValueError(f"cannot derive a slug from name {name!r}")
    return slug


def _check_id(framework_id: str) -> None:
    if not re.fullmatch(r"[0-9]{2}", framework_id):
        raise ValueError(f"framework id must be two digits, got {framework_id!r}")


def _check_topics(topics: list[str]) -> None:
    unknown = [t for t in topics if t not in TOPICS]
    if unknown:
        raise ValueError(
            f"unknown topic(s): {', '.join(unknown)}. "
            f"Known topics: {', '.join(sorted(TOPICS))}"
        )
    if not topics:
        raise ValueError("at least one topic is required (--topics)")


def wrapper_text(framework_id: str, name: str, topic: str, image: str, entrypoint: str) -> str:
    spec = TOPICS[topic]
    slug = slugify(name)
    env_id = re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_")
    entry = [spec["contract"]]
    if spec["budget"]:
        entry.append(spec["budget"])
    return WRAPPER.format(
        slug=f"{framework_id}_{slug}",
        topic=topic,
        label=spec["label"],
        name=name,
        envid=env_id,
        entry_paths="\n".join(entry),
        injection=(
            "native framework client reads OPENAI_API_KEY, OPENAI_BASE_URL "
            "and OPENAI_MODEL from the environment"
        ),
        marker=f"{env_id}_{topic.upper()}_NATIVE",
        image=image,
        entrypoint=entrypoint,
        name_upper=env_id,
        contract_name=Path(spec["contract"]).name,
        runner=spec["runner"],
    )


def manifest_payload(
    framework_id: str,
    name: str,
    topics: list[str],
    upstream_url: str,
    license_spdx: str,
    image: str,
    entrypoint: str,
) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "framework_id": framework_id,
        "name": name,
        "upstream_url": upstream_url,
        "upstream_commit": "0" * 40,
        "license_spdx": license_spdx,
        "native_entrypoint": entrypoint,
        "native_entrypoint_source": "TODO: cite the file and line you took this from",
        "admission_status": "candidate_requires_runtime_evidence",
        "supported_topics": topics,
        "required_env": ["OPENAI_BASE_URL", "OPENAI_API_KEY", "OPENAI_MODEL"],
        "required_images": [image],
        "patches": [],
    }


def scaffold(
    *,
    framework_id: str,
    name: str,
    topics: list[str],
    upstream_url: str,
    license_spdx: str,
    image: str,
    entrypoint: str,
    out_dir: Path,
    force: bool = False,
) -> list[Path]:
    """Write the adapter manifest and one wrapper per topic. Returns written paths."""
    _check_id(framework_id)
    _check_topics(topics)

    slug = slugify(name)
    written: list[Path] = []

    adapter_dir = out_dir / "adapters" / f"{framework_id}-{slug.replace('_', '-')}"
    manifest_path = adapter_dir / "manifest.json"
    payload = manifest_payload(
        framework_id, name, topics, upstream_url, license_spdx, image, entrypoint
    )
    targets = [(manifest_path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")]
    for topic in topics:
        scripts_dir = out_dir / "real_eval" / "scripts"
        wrapper_path = scripts_dir / f"{framework_id}_{slug}_{topic}_fullrun.sh"
        targets.append((wrapper_path, wrapper_text(framework_id, name, topic, image, entrypoint)))

    existing = [p for p, _ in targets if p.exists()]
    if existing and not force:
        raise FileExistsError(
            "refusing to overwrite: " + ", ".join(str(p) for p in existing) + " (use --force)"
        )

    for path, text in targets:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        if path.suffix == ".sh":
            path.chmod(0o755)
        written.append(path)
    return written
