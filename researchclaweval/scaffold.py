"""Scaffolding for new framework adapters.

Generates the two files a new framework needs to run under this harness: the
adapter manifest that records what was pinned, and a wrapper per topic that
declares how to launch the framework. See real_eval/docs/wrapper_interface.md
for what the wrapper's variables mean.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

